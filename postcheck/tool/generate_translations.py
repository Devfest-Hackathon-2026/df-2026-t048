"""Generate the offline Dart catalog: python3 tool/generate_translations.py."""
import json
import re
from pathlib import Path
root = Path(__file__).resolve().parents[1]
def dart_string(value):
    return json.dumps(value, ensure_ascii=False).replace('$', '\\$')

reference = json.loads((root / 'lib/l10n/en.json').read_text())
for code, name in [('en', 'english')]:
    entries = json.loads((root / f'lib/l10n/{code}.json').read_text())
    if entries.keys() != reference.keys():
        raise ValueError(f'{code}: translation keys differ from en.json')
    for key, value in entries.items():
        if not value or sorted(re.findall(r'\{\d+\}', key)) != sorted(re.findall(r'\{\d+\}', value)):
            raise ValueError(f'{code}: invalid translation for {key!r}')
    (root / f'lib/l10n/{name}.dart').write_text(
        f'// Generated by tool/generate_translations.py from {code}.json.\n'
        f'const {name} = <String, String>{{\n' + ''.join(
            f'  {dart_string(key)}: {dart_string(value)},\n' for key, value in entries.items()
        ) + '};\n'
    )
